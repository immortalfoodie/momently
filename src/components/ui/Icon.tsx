export interface IconProps extends SVGProps<SVGSVGElement> {
  name: IconName;
  size?: number;
  className?: string;
  'aria-label'?: string;
}

/**
 * Compact, standalone SVG icon primitive.
 *
 * ACCESSIBILITY DECISION (WHY):
 * Decorative icons default to `aria-hidden="true"` so that screen readers do not stutter
 * or read redundant visual symbols. When an icon acts as a standalone interactive control
 * (e.g. an icon button), providing `aria-label` will automatically clear `aria-hidden` and
 * expose `role="img"` to assistive technology.
 */
export function Icon({
  name,
  size = 20,
  className = '',
  'aria-label': ariaLabel,
  ...props
}: IconProps) {
  const isAriaHidden = ariaLabel ? undefined : true;
  const role = ariaLabel ? 'img' : undefined;

  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={2}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden={isAriaHidden}
      aria-label={ariaLabel}
      role={role}
      className={`inline-block shrink-0 ${className}`}
      {...props}
    >
      {renderIconPath(name)}
    </svg>
  );
}

